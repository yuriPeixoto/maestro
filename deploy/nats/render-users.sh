#!/bin/sh
# Writes the nats-server accounts block (ADR-015): the operator, plus one user per monitored server
# that may only publish its own data and only hear its own commands. Public keys only: the output
# holds no secret.
#
# Usage: render-users.sh ADMIN_PUBLIC_KEY SERVER=PUBLIC_KEY [SERVER=PUBLIC_KEY ...] > users.conf
#
# SERVER is the server id the agent reports (its hostname), and it becomes one NATS subject token,
# so it must match [a-z0-9_-]+. Public keys come from `nk -inkey <seed file> -pubout`.
set -eu

fail() { echo "render-users: $*" >&2; exit 65; }

is_user_public_key() {
  case $1 in
    U*) [ "${#1}" -eq 56 ] && [ -z "$(printf '%s' "$1" | tr -d 'A-Z2-7')" ] ;;
    *) false ;;
  esac
}

[ $# -ge 2 ] || { echo "usage: $0 ADMIN_PUBLIC_KEY SERVER=PUBLIC_KEY [...]" >&2; exit 64; }

admin=$1
shift
is_user_public_key "$admin" || fail "not a user public key: $admin"

# Validate everything before writing, so a bad argument never leaves half a file behind.
seen_names=" "
seen_keys=" $admin "
for pair in "$@"; do
  name=${pair%%=*}
  key=${pair#*=}
  case $name in
    '' | *[!a-z0-9_-]*) fail "server name must be one token of [a-z0-9_-]: '$name'" ;;
  esac
  case $seen_names in
    *" $name "*) fail "server listed twice: $name" ;;
  esac
  is_user_public_key "$key" || fail "not a user public key for $name: $key"
  case $seen_keys in
    *" $key "*) fail "key used twice (each server needs its own): $name" ;;
  esac
  seen_names="$seen_names$name "
  seen_keys="$seen_keys$key "
done

cat <<EOF
# Generated by deploy/nats/render-users.sh. Public keys only.
accounts {
  MAESTRO {
    jetstream: enabled
    users: [
      # Operator, for the nats CLI on the NATS host only. No limits.
      { nkey: $admin }
EOF

for pair in "$@"; do
  name=${pair%%=*}
  key=${pair#*=}
  cat <<EOF
      # $name: publishes maestro.ingest.$name.>, hears maestro.cmd.$name, answers what it was asked.
      {
        nkey: $key
        permissions: {
          publish: { allow: ["maestro.ingest.$name.>"] }
          subscribe: { allow: ["maestro.cmd.$name", "_INBOX_$name.>"] }
          allow_responses: { max: 1, expires: "1m" }
        }
      }
EOF
done

cat <<EOF
    ]
  }
}
EOF
